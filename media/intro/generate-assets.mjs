import { readFile, writeFile } from 'node:fs/promises'
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const root = new URL('../../', import.meta.url)
const load = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'))
const topology = await load('src/assets/china-overview.topo.json')
const china = feature(topology, topology.objects.regions)
const province = await load('data/maps/330000.json')
const city = await load('data/maps/330100.json')
function normalize(collection) {
  const ring = (points, exterior) => {
    let area = 0
    for (let i = 0; i < points.length; i++) {
      const a = points[i], b = points[(i + 1) % points.length]
      area += a[0] * b[1] - b[0] * a[1]
    }
    return (area < 0) === exterior ? points : [...points].reverse()
  }
  return { ...collection, features: collection.features.map(f => {
    const geometry = f.geometry
    return geometry.type === 'Polygon' ? { ...f, geometry: { ...geometry, coordinates: geometry.coordinates.map((r, i) => ring(r, i === 0)) } }
      : geometry.type === 'MultiPolygon' ? { ...f, geometry: { ...geometry, coordinates: geometry.coordinates.map(p => p.map((r, i) => ring(r, i === 0))) } } : f
  }) }
}
function project(collection, country = false) {
  const normalized = normalize(collection)
  const projection = geoMercator()
  projection.fitExtent([[70, 65], [1030, 805]], country
    ? { type: 'MultiPoint', coordinates: [[73, 53.6], [135.2, 17.8]] } : normalized)
  const path = geoPath(projection).digits(1)
  return normalized.features.filter(f => /^\d{6}$/.test(String(f.properties.adcode))).map(f => {
    const center = f.properties.centroid || f.properties.center
    const point = center ? projection(center) : path.centroid(f)
    return { code: String(f.properties.adcode), name: f.properties.name, d: path(f), x: point[0], y: point[1] }
  })
}
const data = { china: project(china, true), zhejiang: project(province), hangzhou: project(city) }
await writeFile(new URL('map-data.js', import.meta.url), `// DataV.GeoAtlas administrative outlines; generated by generate-assets.mjs.\nwindow.PROMO_MAPS=${JSON.stringify(data)};\n`)
console.log('Generated local SVG outline data, with no map SDK or API key.')
