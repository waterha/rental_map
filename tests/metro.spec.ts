import { test, expect } from '@playwright/test'

test('metro control is city-only and Hangzhou lines follow pan/zoom and turn off', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/metro/')) requests.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('button', { name: '进入浙江省', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '地铁图层', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '进入浙江省', exact: true }).press('Enter')
  await expect(page.getByRole('button', { name: '进入杭州市', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '地铁图层', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '进入杭州市', exact: true }).press('Enter')
  const toggle = page.getByRole('button', { name: '地铁图层', exact: true })
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  expect(requests).toHaveLength(0)
  await toggle.click()
  await expect(page.locator('.metro-route').first()).toBeVisible()
  await expect(toggle).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.metro-status')).toContainText('站点连线示意')
  await expect(page.locator('.metro-legend')).toContainText('1号线')
  expect(await page.locator('.metro-route').count()).toBeGreaterThan(10)
  await expect(page.locator('.metro-station')).toHaveCount(0)
  await page.screenshot({ path: '.local/metro-hangzhou-overview.png' })
  const original = await page.locator('.metro-route').first().getAttribute('d')
  await page.mouse.move(750,450); await page.mouse.wheel(0,-250); await page.mouse.wheel(0,-250)
  await expect.poll(async () => Number(await page.locator('.map-camera').getAttribute('data-zoom'))).toBeGreaterThan(1.8)
  await expect(page.locator('.metro-station').first()).toBeVisible()
  expect(await page.locator('.metro-route').first().getAttribute('d')).toBe(original)
  await page.screenshot({ path: '.local/metro-hangzhou.png' })
  const pan = Number(await page.locator('.map-camera').getAttribute('data-pan-x'))
  await page.mouse.move(700,400); await page.mouse.down(); await page.mouse.move(820,460,{steps:8}); await page.mouse.up()
  await expect.poll(async () => Number(await page.locator('.map-camera').getAttribute('data-pan-x'))).toBeCloseTo(pan+120,0)
  await expect(page.locator('.map-breadcrumbs')).toHaveText('中国/浙江省/杭州市')
  await toggle.click(); await expect(page.locator('.metro-layer')).toHaveCount(0)
  await toggle.click(); await expect(page.locator('.metro-route').first()).toBeVisible()
  expect(requests).toHaveLength(1)
  await page.getByRole('button', { name: '进入西湖区', exact: true }).press('Enter')
  await expect(toggle).toHaveCount(0)
  await page.getByRole('button', { name: '杭州市', exact: true }).click()
  await expect(toggle).toHaveAttribute('aria-pressed','false')
  await expect(page.locator('.metro-layer')).toHaveCount(0)
})

test('metro failures retry, empty coverage is honest, and controls fit mobile', async ({ page }) => {
  await page.setViewportSize({ width:390, height:844 })
  await page.route('**/api/metro/330100', route => route.fulfill({ status:502, json:{error:'地铁线路暂时加载失败，请重试'} }))
  await page.goto('/?region=330100')
  const toggle = page.getByRole('button',{name:'地铁图层',exact:true})
  await toggle.click()
  await expect(page.locator('.metro-status')).toContainText('地铁线路暂时加载失败')
  await page.route('**/api/metro/330100', route => route.fulfill({ json:{cityCode:'330100',cityName:'杭州市',source:'高德地铁',schematic:true,stale:false,fetchedAt:new Date().toISOString(),lines:[]} }))
  await page.getByRole('button',{name:'重试',exact:true}).click()
  await expect(page.locator('.metro-status')).toContainText('暂无收录')
  await expect(page.locator('.metro-route')).toHaveCount(0)
  const bounds=await page.locator('.metro-tools').boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390)
  await page.screenshot({path:'.local/metro-mobile.png'})
  await page.unroute('**/api/metro/330100')
  await page.reload()
  await toggle.click()
  await expect(page.locator('.metro-route').first()).toBeVisible()
  await page.screenshot({path:'.local/metro-mobile-lines.png'})
})

