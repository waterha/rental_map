import { test, expect } from '@playwright/test'

test('metro is district-only, sits top left, follows AMap camera and cleans up', async ({ page }) => {
  test.setTimeout(90000)
  const requests: string[] = []
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/metro/')) requests.push(new URL(request.url()).pathname) })
  await page.goto('/')
  await page.getByRole('button', { name: '进入浙江省', exact: true }).press('Enter')
  await expect(page.getByRole('button', { name: '地铁图层', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '进入杭州市', exact: true }).press('Enter')
  const toggle = page.getByRole('button', { name: '地铁图层', exact: true })
  await expect(toggle).toHaveCount(0)
  await page.getByRole('button', { name: '进入西湖区', exact: true }).press('Enter')
  await expect(toggle).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.rental-light').first()).toBeVisible({ timeout:55000 })
  expect(requests).toHaveLength(0)
  const bounds = await toggle.boundingBox()
  expect(bounds!.x).toBeLessThan(60); expect(bounds!.y).toBeLessThan(110)
  const account = await page.locator('.account-trigger').boundingBox()
  expect(bounds!.y).toBeGreaterThan(account!.y + account!.height)
  await toggle.click()
  await expect.poll(async () => Number(await page.locator('.district-map').getAttribute('data-metro-lines'))).toBeGreaterThan(0)
  await expect(page.locator('.metro-station-pin').first()).toBeVisible()
  await expect(page.locator('.metro-status')).toContainText('站点连线示意')
  expect(requests).toEqual(['/api/metro/330106'])
  await page.screenshot({ path:'.local/metro-district.png' })
  const zoom = Number(await page.locator('.district-map').getAttribute('data-zoom'))
  await page.mouse.move(750,450); await page.mouse.wheel(0,-300)
  await expect.poll(async () => Number(await page.locator('.district-map').getAttribute('data-zoom'))).toBeGreaterThan(zoom)
  const center = await page.locator('.district-map').getAttribute('data-center')
  await page.mouse.move(700,400); await page.mouse.down(); await page.mouse.move(820,460,{steps:8}); await page.mouse.up()
  await expect.poll(async () => page.locator('.district-map').getAttribute('data-center')).not.toBe(center)
  await toggle.click()
  await expect(page.locator('.district-map')).toHaveAttribute('data-metro-lines','0')
  await expect(page.locator('.metro-station-pin')).toHaveCount(0)
  await toggle.click()
  await expect.poll(async () => Number(await page.locator('.district-map').getAttribute('data-metro-lines'))).toBeGreaterThan(0)
  expect(requests).toHaveLength(1)
  await page.getByRole('button',{name:'杭州市',exact:true}).click()
  await expect(toggle).toHaveCount(0)
  await page.getByRole('button',{name:'进入西湖区',exact:true}).press('Enter')
  await expect(toggle).toHaveAttribute('aria-pressed','false')
})

test('district metro retries and fits mobile with no overlap', async ({ page }) => {
  await page.setViewportSize({width:390,height:844})
  await page.route('https://webapi.amap.com/maps?**', route => route.abort())
  await page.route('**/api/metro/330106', route => route.fulfill({status:502,json:{error:'地铁线路暂时加载失败，请重试'}}))
  await page.goto('/?region=330106')
  const toggle=page.getByRole('button',{name:'地铁图层',exact:true})
  await toggle.click()
  await expect(page.locator('.metro-status')).toContainText('地铁线路暂时加载失败')
  await page.route('**/api/metro/330106', route => route.fulfill({json:{cityCode:'330100',cityName:'杭州市',source:'高德地铁',schematic:true,stale:false,fetchedAt:new Date().toISOString(),lines:[]}}))
  await page.getByRole('button',{name:'重试',exact:true}).click()
  await expect(page.locator('.metro-status')).toContainText('暂无收录')
  const bounds=await page.locator('.metro-tools').boundingBox()
  expect(bounds!.x).toBeLessThan(30); expect(bounds!.y).toBeLessThan(100)
  expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390)
  const account=await page.locator('.account-trigger').boundingBox()
  expect(bounds!.y).toBeGreaterThan(account!.y+account!.height)
  await page.screenshot({path:'.local/metro-district-mobile.png'})
})

test('municipality metro opens in its districts only', async ({page})=>{
  await page.route('https://webapi.amap.com/maps?**', route => route.abort())
  await page.goto('/?region=110000')
  const toggle=page.getByRole('button',{name:'地铁图层',exact:true})
  await expect(page.getByRole('button',{name:'进入海淀区',exact:true})).toBeVisible()
  await expect(toggle).toHaveCount(0)
  await page.getByRole('button',{name:'进入海淀区',exact:true}).press('Enter')
  await expect(toggle).toHaveAttribute('aria-pressed','false')
})
