test('boundary fetch failure can be retried', async ({ page }) => {
  await page.route('**/api/maps/350000', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: '该区域边界暂不可用' }) }))
  await page.getByRole('button', { name: '进入福建省', exact: true }).press('Enter')
  await expect(page.getByRole('alert')).toContainText('暂不可用')
  await page.unroute('**/api/maps/350000')
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await expect(page.getByRole('button', { name: '进入厦门市', exact: true })).toBeVisible()
})

test('AMap connection error is visible and breadcrumb still returns to city', async ({ page }) => {
  await page.route('https://webapi.amap.com/maps?**', route => route.abort())
  await page.getByRole('button', { name: '进入浙江省', exact: true }).press('Enter')
  await page.getByRole('button', { name: '进入杭州市', exact: true }).press('Enter')
  await page.getByRole('button', { name: '进入西湖区', exact: true }).press('Enter')
  await expect(page.getByRole('alert')).toContainText('高德地图加载失败')
  await page.getByRole('button', { name: '杭州市', exact: true }).click()
  await expect(page.getByRole('button', { name: '进入西湖区', exact: true })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
})
