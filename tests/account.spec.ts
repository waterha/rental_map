import { test, expect } from '@playwright/test'

test('real backend enforces mailbox rules and reports missing SMTP honestly', async ({ page, request }) => {
  const configResponse = await request.get('/api/auth/config')
  expect(configResponse.ok()).toBeTruthy()
  const config = await configResponse.json()
  expect(config.codeExpiresIn).toBe(120)
  const invalid = await request.post('/api/auth/code', { data: { email: 'someone@qq.com.evil.invalid' } })
  expect(invalid.status()).toBe(400)
  const unverified = await request.post('/api/auth/register', { data: { email: 'testuser@qq.com', password: 'Test-only-password123!', code: '123456' } })
  expect(unverified.status()).toBe(400)
  await page.goto('/')
  await page.getByRole('button', { name: '注册或登录', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '邮箱账号' })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('验证码 2 分钟内有效')
  await dialog.getByLabel('邮箱地址', { exact: true }).fill('anyone@madeup.invalid')
  await expect(dialog.getByRole('button', { name: '发送验证码', exact: true })).toBeDisabled()
  await dialog.getByLabel('邮箱地址', { exact: true }).fill('testuser@qq.com')
  if (!config.mailAvailable) {
    await expect(dialog).toContainText('邮件服务尚未配置')
    await expect(dialog.getByRole('button', { name: '发送验证码', exact: true })).toBeDisabled()
    const unavailable = await request.post('/api/auth/code', { data: { email: 'testuser@qq.com' } })
    expect(unavailable.status()).toBe(503)
  }
  await dialog.getByRole('button', { name: '账号登录', exact: true }).click()
  await dialog.getByLabel('密码', { exact: true }).fill('Wrong-password123!')
  await dialog.getByRole('button', { name: '登录', exact: true }).click()
  await expect(dialog.getByRole('alert')).toHaveText('邮箱或密码错误')
  await page.screenshot({ path: '.local/account-desktop.png' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('.atlas-svg')).toBeVisible()
})

// UI state tests use mocked responses; OTP validity and account creation use the real Go tests.
test('registration UI handles mail countdown, verifies server result, and never stores secrets', async ({ page }) => {
  await page.route('**/api/auth/config', route => route.fulfill({ json: { allowedDomains: ['qq.com', '163.com'], codeExpiresIn: 120, resendAfter: 60, mailAvailable: true, passwordMinLength: 10, passwordMaxBytes: 72 } }))
  await page.route('**/api/auth/code', route => route.fulfill({ json: { message: 'sent', expiresIn: 120, resendAfter: 60 } }))
  await page.route('**/api/auth/register', async route => {
    const body = route.request().postDataJSON()
    expect(body.email).toBe('testuser@qq.com')
    expect(body.code).toBe('123456')
    await route.fulfill({ status: 201, json: { user: { id: 'test-user', email: body.email } } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: '注册或登录', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('邮箱地址', { exact: true }).fill('testuser@qq.com')
  await dialog.getByLabel('密码', { exact: true }).fill('Test-only-password123!')
  await dialog.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('验证码已发送')
  await expect(dialog.getByRole('button', { name: /后重发/ })).toBeDisabled()
  await expect(dialog.locator('.code-guidance')).toContainText(/验证码剩余 [12]:/)
  await dialog.getByLabel('邮箱验证码', { exact: true }).fill('123456')
  await dialog.getByRole('button', { name: '验证邮箱并注册', exact: true }).click()
  await expect(dialog).toContainText('验证成功，欢迎加入')
  await expect(dialog).toContainText('testuser@qq.com')
  expect(await page.evaluate(() => JSON.stringify(localStorage) + JSON.stringify(sessionStorage))).not.toContain('Test-only-password123!')
  expect(await page.evaluate(() => JSON.stringify(localStorage) + JSON.stringify(sessionStorage))).not.toContain('123456')
})

test('registration UI expires code and binds it to the email used for delivery', async ({ page }) => {
  await page.clock.install()
  await page.route('**/api/auth/config', route => route.fulfill({ json: { allowedDomains: ['qq.com'], codeExpiresIn: 120, resendAfter: 60, mailAvailable: true, passwordMinLength: 10, passwordMaxBytes: 72 } }))
  await page.route('**/api/auth/code', route => route.fulfill({ json: { expiresIn: 120, resendAfter: 60 } }))
  await page.goto('/')
  await page.getByRole('button', { name: '注册或登录', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('邮箱地址', { exact: true }).fill('testuser@qq.com')
  await dialog.getByLabel('密码', { exact: true }).fill('Test-only-password123!')
  await dialog.getByRole('button', { name: '发送验证码', exact: true }).click()
  await expect(dialog.getByRole('status')).toBeVisible()
  await dialog.getByLabel('邮箱验证码', { exact: true }).fill('123456')
  await page.clock.fastForward(120000)
  await expect(dialog.locator('.code-guidance')).toContainText('验证码已过期')
  await expect(dialog.getByRole('button', { name: '验证邮箱并注册', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '重新发送', exact: true }).click()
  await dialog.getByLabel('邮箱验证码', { exact: true }).fill('123456')
  await dialog.getByLabel('邮箱地址', { exact: true }).fill('another@qq.com')
  await expect(dialog.getByLabel('邮箱验证码', { exact: true })).toHaveValue('')
  await expect(dialog.getByRole('button', { name: '验证邮箱并注册', exact: true })).toBeDisabled()
})

test('account dialog fits mobile and traps keyboard focus', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '注册或登录', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.getByLabel('邮箱地址', { exact: true })).toBeVisible()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: '关闭账号窗口', exact: true })).toBeFocused()
  await page.screenshot({ path: '.local/account-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '注册或登录', exact: true })).toBeFocused()
})
